// Generates src/usecases/index.ts + src/usecases/slugs.ts from
// src/usecases/<slug>/usecase.ts — full-parity mirror of the web app's
// generator (descriptor + pages per scope + childPages + profile + widget +
// activation + settings). A folder is a module when it contains usecase.ts.
import {existsSync, readdirSync, writeFileSync} from 'node:fs';
import {join} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const modulesDir = join(root, 'src', 'usecases');
const indexOut = join(modulesDir, 'index.ts');
const slugsOut = join(modulesDir, 'slugs.ts');

const scopes = ['org', 'node'];

const slugs = readdirSync(modulesDir, {withFileTypes: true})
  .filter(e => e.isDirectory())
  .map(e => e.name)
  .filter(slug => existsSync(join(modulesDir, slug, 'usecase.ts')))
  .sort();

const imports = [];
const entries = [];

slugs.forEach((slug, i) => {
  const m = `m${i}_${slug.replace(/[^a-zA-Z0-9_]/g, '_')}`;
  imports.push(`import ${m} from './${slug}/usecase';`);

  const pages = {};
  for (const scope of scopes) {
    const file = join(modulesDir, slug, 'dashboard', `${scope}.tsx`);
    if (existsSync(file)) {
      const p = `${m}_${scope}`;
      imports.push(`import ${p} from './${slug}/dashboard/${scope}';`);
      pages[scope] = p;
    }
  }

  const hasActivation = existsSync(
    join(modulesDir, slug, 'activation', 'page.tsx'),
  );
  const a = hasActivation ? `${m}_activation` : null;
  if (hasActivation) {
    imports.push(`import ${a} from './${slug}/activation/page';`);
  }

  const hasProfile = existsSync(
    join(modulesDir, slug, 'dashboard', 'profile.tsx'),
  );
  const prof = hasProfile ? `${m}_profile` : null;
  if (hasProfile) {
    imports.push(`import ${prof} from './${slug}/dashboard/profile';`);
  }

  const hasWidget = existsSync(
    join(modulesDir, slug, 'dashboard', 'widget.tsx'),
  );
  const wid = hasWidget ? `${m}_widget` : null;
  if (hasWidget) {
    imports.push(`import ${wid} from './${slug}/dashboard/widget';`);
  }

  const hasSettings = existsSync(join(modulesDir, slug, 'settings.tsx'));
  const set = hasSettings ? `${m}_settings` : null;
  if (hasSettings) {
    imports.push(`import ${set} from './${slug}/settings';`);
  }

  const pagesDir = join(modulesDir, slug, 'dashboard', 'pages');
  const childPages = {};
  if (existsSync(pagesDir)) {
    for (const entry of readdirSync(pagesDir, {withFileTypes: true})) {
      if (!entry.isFile() || !entry.name.endsWith('.tsx')) {
        continue;
      }
      const base = entry.name.slice(0, -'.tsx'.length);
      const cp = `${m}_page_${base.replace(/[^a-zA-Z0-9_]/g, '_')}`;
      imports.push(`import ${cp} from './${slug}/dashboard/pages/${base}';`);
      childPages[base] = cp;
    }
  }

  const pageEntries = Object.entries(pages)
    .map(([scope, ident]) => `      ${scope}: ${ident},`)
    .join('\n');
  const childPageEntries = Object.entries(childPages)
    .map(([base, ident]) => `      ${base}: ${ident},`)
    .join('\n');

  entries.push(
    `  '${slug}': {\n` +
      `    descriptor: ${m},\n` +
      `    pages: {\n${pageEntries}\n    },\n` +
      (prof ? `    profile: ${prof},\n` : '') +
      (wid ? `    widget: ${wid},\n` : '') +
      (a ? `    activation: ${a},\n` : '') +
      (set ? `    settings: ${set},\n` : '') +
      (childPageEntries
        ? `    childPages: {\n${childPageEntries}\n    },\n`
        : '') +
      `  },`,
  );
});

const indexContent = [
  '// AUTO-GENERATED by scripts/gen-usecase-modules.mjs — DO NOT EDIT.',
  '// Drop a module under src/usecases/<slug>/ (usecase.ts + dashboard/* + activation/page.tsx + dashboard/profile.tsx + settings.tsx).',
  "import type { ComponentType } from 'react';",
  "import type { UsecaseModuleDescriptor, UsecaseModuleScope, UsecaseSettingsProps } from './_types';",
  '',
  ...imports,
  '',
  'export type ScopePages = Partial<Record<UsecaseModuleScope, ComponentType>>;',
  '',
  'export interface UsecaseModule {',
  '  descriptor: UsecaseModuleDescriptor;',
  '  /** Dashboard page per scope. Absent scope → platform shows DashboardUnavailable. */',
  '  pages: ScopePages;',
  '  /** Usecase-owned child pages (dashboard/pages/*.tsx), keyed by file basename. */',
  '  childPages?: Record<string, ComponentType>;',
  '  /** Usecase-owned profile screen (dashboard/profile.tsx). */',
  '  profile?: ComponentType;',
  '  /** Overview widget (dashboard/widget.tsx). */',
  '  widget?: ComponentType;',
  '  /** Activation page (activation/page.tsx). */',
  '  activation?: ComponentType;',
  '  /** Settings panel (settings.tsx). */',
  '  settings?: ComponentType<UsecaseSettingsProps>;',
  '}',
  '',
  'const USECASE_MODULES: Record<string, UsecaseModule> = {',
  ...entries,
  '};',
  '',
  'export function getUsecaseModule(slug: string): UsecaseModule | undefined {',
  '  return USECASE_MODULES[slug];',
  '}',
  '',
  'export function listUsecaseModules(): UsecaseModule[] {',
  '  return Object.values(USECASE_MODULES);',
  '}',
  '',
].join('\n');

const slugsContent = [
  '// AUTO-GENERATED by scripts/gen-usecase-modules.mjs — DO NOT EDIT.',
  `export const USECASE_MODULE_SLUGS = [${slugs
    .map(s => `'${s}'`)
    .join(', ')}] as const;`,
  '',
  'export function isUsecaseModule(slug: string): boolean {',
  '  return (USECASE_MODULE_SLUGS as readonly string[]).includes(slug);',
  '}',
  '',
].join('\n');

writeFileSync(indexOut, indexContent);
writeFileSync(slugsOut, slugsContent);
console.log(
  `Generated usecase module manifest for: ${slugs.join(', ') || '(none)'}`,
);
